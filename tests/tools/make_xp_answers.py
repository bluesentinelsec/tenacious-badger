"""Write tests/core/xp_answers.h: known answers for the arithmetic tests.

    python tests/tools/make_xp_answers.py

The tests compute factorials, powers of two, and Fibonacci numbers with the
engine's own arithmetic and compare the text of each with the value here,
which Python's integers compute independently. Run this only to change the
set of answers; the output is checked in, and the build never runs it.

The output is formatted with the clang-format on PATH, or the one that the
CLANG_FORMAT environment variable names, as the format check expects.
"""
import os
from pathlib import Path
import subprocess

OUTPUT = Path(__file__).resolve().parent.parent / 'core' / 'xp_answers.h'

FACTORIALS = [0, 1, 2, 3, 10, 12, 13, 20, 21, 25, 34, 35, 50, 100, 170, 200]
POWERS_OF_TWO = [0, 1, 31, 32, 33, 63, 64, 65, 95, 96, 127, 128, 1000, 4095, 4096]
FIBONACCI = [0, 1, 2, 47, 48, 93, 94, 95, 100, 1000, 2000]

# The longest piece of a string literal on one line, which keeps the file
# within the column limit of the formatter.
PIECE = 80


def factorial(n):
    product = 1
    for factor in range(2, n + 1):
        product *= factor
    return product


def fibonacci(n):
    previous, current = 0, 1
    for _ in range(n):
        previous, current = current, previous + current
    return previous


def literal(text):
    pieces = [text[start:start + PIECE] for start in range(0, len(text), PIECE)]
    return '\n'.join(f'         "{piece}"' for piece in pieces)


def table(name, comment, rows):
    lines = [f'/* {comment} */', f'static const xp_answer {name}[] = {{']
    for argument, number in rows:
        lines.append(f'    {{{argument},')
        lines.append(literal(str(number)) + ',')
        lines.append(literal(format(number, 'x')) + '},')
    lines.append('};')
    return '\n'.join(lines)


def main():
    parts = [
        '/* Known answers for xp_test.c, computed by Python\'s integers.',
        ' * Generated by tests/tools/make_xp_answers.py; change that script, not this file. */',
        '#ifndef TB_XP_ANSWERS_H',
        '#define TB_XP_ANSWERS_H',
        '',
        '#include <stddef.h>',
        '',
        '/* A function of a small argument, as text in base 10 and in base 16. */',
        'typedef struct xp_answer',
        '{',
        '    size_t argument;',
        '    const char *decimal;',
        '    const char *hexadecimal;',
        '} xp_answer;',
        '',
        table('xp_factorials', 'n!', [(n, factorial(n)) for n in FACTORIALS]),
        '',
        table('xp_powers_of_two', '2^n', [(n, 1 << n) for n in POWERS_OF_TWO]),
        '',
        table('xp_fibonacci', 'F(n), where F(0) = 0 and F(1) = 1',
              [(n, fibonacci(n)) for n in FIBONACCI]),
        '',
        '#endif',
        '',
    ]
    OUTPUT.write_bytes('\n'.join(parts).encode())
    subprocess.run([os.environ.get('CLANG_FORMAT', 'clang-format'), '-i', str(OUTPUT)],
                   check=True)


if __name__ == '__main__':
    main()
