"""Write tests/core/ap_vectors.h: arbitrary-precision results to test against.

    python tests/tools/make_ap_vectors.py

Python's integers are an implementation of arbitrary-precision arithmetic that
shares no code with the engine's, and its `//` and `%` round toward negative
infinity, as tb_ap_div_floor and tb_ap_mod_floor do. This script draws random
operands of many sizes and signs from a fixed seed and records what Python
computes from them: each operation on pairs of operands, modular and plain
powers, and long chains of operations. Run it only to change the vectors; the
output is checked in, and the build never runs it.

The output is formatted with the clang-format on PATH, or the one that the
CLANG_FORMAT environment variable names, as the format check expects.
"""
import os
from pathlib import Path
import random
import subprocess

OUTPUT = Path(__file__).resolve().parent.parent / 'core' / 'ap_vectors.h'
SEED = 20261117

# Sizes in bits, chosen around the boundaries of 32-bit digits.
BIT_LENGTHS = [1, 2, 31, 32, 33, 63, 64, 65, 96, 127, 128, 129, 200, 333, 640, 1000]
PAIR_COUNT = 60
POWER_COUNT = 24
CHAIN_COUNT = 16
CHAIN_STEPS = 40
# A chain keeps its value below this many bits, so that the vectors stay small.
CHAIN_BIT_LIMIT = 2000

PIECE = 76


def hexadecimal(number):
    return format(number, 'x')


def literal(text, indent):
    pieces = [text[start:start + PIECE] for start in range(0, len(text), PIECE)] or ['']
    return '\n'.join(f'{indent}"{piece}"' for piece in pieces)


def random_number(rng, allow_zero=True):
    bits = rng.choice(BIT_LENGTHS)
    magnitude = rng.getrandbits(bits) | (1 << (bits - 1))
    if rng.random() < 0.25:
        # All ones, or one past: where every digit carries.
        magnitude = (1 << bits) - 1 if rng.random() < 0.5 else 1 << bits
    if allow_zero and rng.random() < 0.08:
        return 0
    return -magnitude if rng.random() < 0.5 else magnitude


def pair_rows(rng):
    rows = []
    for _ in range(PAIR_COUNT):
        a = random_number(rng)
        b = random_number(rng, allow_zero=False)
        rows.append([a, b, a + b, a - b, a * b, a // b, a % b])
    return rows


def power_rows(rng):
    rows = []
    for index in range(POWER_COUNT):
        base = random_number(rng)
        if index % 2 == 0:
            exponent = rng.getrandbits(rng.choice([1, 8, 64, 200, 300]))
            modulus = abs(random_number(rng, allow_zero=False))
            rows.append((base, exponent, modulus, pow(base, exponent, modulus)))
        else:
            # Without a modulus the result grows with the exponent, so the
            # base stays within 64 bits.
            base = rng.randrange(-(1 << 64), 1 << 64)
            exponent = rng.randrange(0, 80)
            rows.append((base, exponent, None, base ** exponent))
    return rows


def chain(rng):
    value = random_number(rng)
    start = value
    steps = []
    for _ in range(CHAIN_STEPS):
        operation = rng.choice('+-*/%<>^')
        if operation == '^' and (abs(value).bit_length() > CHAIN_BIT_LIMIT // 4 or value == 0):
            operation = '+'
        if operation in '*<' and abs(value).bit_length() > CHAIN_BIT_LIMIT:
            operation = '/'
        if operation in '<>':
            operand = rng.randrange(0, 200)
            value = value << operand if operation == '<' else value >> operand
        elif operation == '^':
            operand = rng.randrange(0, 4)
            value = value ** operand
        else:
            operand = random_number(rng, allow_zero=operation in '+-*')
            if operation == '+':
                value = value + operand
            elif operation == '-':
                value = value - operand
            elif operation == '*':
                value = value * operand
            elif operation == '/':
                value = value // operand
            else:
                value = value % operand
        steps.append((operation, operand))
    return start, steps, value


def main():
    rng = random.Random(SEED)
    out = [
        '/* Arbitrary-precision results for ap_test.c, computed by Python\'s integers.',
        ' * Generated by tests/tools/make_ap_vectors.py; change that script, not this file.',
        ' * Every number is text in base 16, with a leading "-" when negative. */',
        '#ifndef TB_AP_VECTORS_H',
        '#define TB_AP_VECTORS_H',
        '',
        '#include <stddef.h>',
        '',
        '/* Two operands and the result of each operation on them. Division rounds',
        ' * toward negative infinity. */',
        'typedef struct ap_pair_vector',
        '{',
        '    const char *a;',
        '    const char *b;',
        '    const char *sum;',
        '    const char *difference;',
        '    const char *product;',
        '    const char *quotient;',
        '    const char *remainder;',
        '} ap_pair_vector;',
        '',
        '/* base^exponent, modulo the modulus when there is one. */',
        'typedef struct ap_power_vector',
        '{',
        '    const char *base;',
        '    const char *exponent;',
        '    const char *modulus; /* NULL for none */',
        '    const char *result;',
        '} ap_power_vector;',
        '',
        '/* One step of a chain: the value so far, the operation, and the operand.',
        ' * The operations are + - * / % (floor division and remainder), < and >',
        ' * (shifts by a count in base 16), and ^ (a power, in base 16). */',
        'typedef struct ap_chain_step',
        '{',
        '    char operation;',
        '    const char *operand;',
        '} ap_chain_step;',
        '',
        'typedef struct ap_chain_vector',
        '{',
        '    const char *start;',
        '    const ap_chain_step *steps;',
        '    size_t step_count;',
        '    const char *result;',
        '} ap_chain_vector;',
        '',
        'static const ap_pair_vector ap_pairs[] = {',
    ]
    for row in pair_rows(rng):
        out.append('    {')
        out.extend(literal(hexadecimal(number), '        ') + ',' for number in row)
        out.append('    },')
    out += ['};', '', 'static const ap_power_vector ap_powers[] = {']
    for base, exponent, modulus, result in power_rows(rng):
        out.append('    {')
        out.append(literal(hexadecimal(base), '        ') + ',')
        out.append(literal(hexadecimal(exponent), '        ') + ',')
        out.append((literal(hexadecimal(modulus), '        ') if modulus is not None
                    else '        NULL') + ',')
        out.append(literal(hexadecimal(result), '        ') + ',')
        out.append('    },')
    out.append('};')
    chains = [chain(rng) for _ in range(CHAIN_COUNT)]
    for index, (_, steps, _) in enumerate(chains):
        out += ['', f'static const ap_chain_step ap_chain_{index}[] = {{']
        for operation, operand in steps:
            out.append(f"    {{'{operation}',")
            out.append(literal(hexadecimal(operand), '     ') + '},')
        out.append('};')
    out += ['', 'static const ap_chain_vector ap_chains[] = {']
    for index, (start, steps, result) in enumerate(chains):
        out.append('    {')
        out.append(literal(hexadecimal(start), '        ') + ',')
        out.append(f'        ap_chain_{index},')
        out.append(f'        sizeof(ap_chain_{index}) / sizeof(ap_chain_{index}[0]),')
        out.append(literal(hexadecimal(result), '        ') + ',')
        out.append('    },')
    out += ['};', '', '#endif', '']
    OUTPUT.write_bytes('\n'.join(out).encode())
    subprocess.run([os.environ.get('CLANG_FORMAT', 'clang-format'), '-i', str(OUTPUT)],
                   check=True)


if __name__ == '__main__':
    main()
