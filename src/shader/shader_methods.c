tb_shader_object_methods tb_shader_object_methods_of(tb_shader_object object)
{
    for (size_t index = 0; index < sizeof(objects) / sizeof(objects[0]); index++)
    {
        if (objects[index].object == object)
        {
            return objects[index].methods;
        }
    }
    const tb_shader_object_methods none = {0};
    return none;
}
