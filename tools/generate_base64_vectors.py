"""Write tests/codec/base64_vectors.h: encodings made by Python's base64 module.

The issue asks that the encoder agree with an independent implementation.
This script encodes deterministic byte strings in all four forms (standard
or URL-safe alphabet, with or without padding) and stores the bytes and the
four texts. tests/codec/base64_test.c encodes and decodes them and compares.

Development time only; the build and the tests need no Python. Run from the
repository root, then format the sources (build.bat fmt).
"""

import base64
from pathlib import Path

LENGTHS = list(range(0, 20)) + [31, 32, 33, 57, 100, 255, 256]


def sample(length):
    state = length * 2654435761 & 0xFFFFFFFF
    out = bytearray()
    for _ in range(length):
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((state >> 16) & 0xFF)
    return bytes(out)


def c_bytes(data):
    if not data:
        return '{0}'
    return '{' + ', '.join(f'0x{byte:02X}' for byte in data) + '}'


def main():
    lines = [
        '/* Generated by tools/generate_base64_vectors.py from Python\'s base64',
        ' * module; do not edit by hand. */',
        '#ifndef TB_BASE64_VECTORS_H',
        '#define TB_BASE64_VECTORS_H',
        '',
        '#include <stddef.h>',
        '',
        'typedef struct base64_vector',
        '{',
        '    const unsigned char *bytes;',
        '    size_t length;',
        '    const char *standard;',
        '    const char *standard_unpadded;',
        '    const char *url;',
        '    const char *url_unpadded;',
        '} base64_vector;',
        '',
    ]
    for length in LENGTHS:
        lines.append(f'static const unsigned char base64_bytes_{length}[] = {c_bytes(sample(length))};')
    lines += ['', 'static const base64_vector base64_vectors[] = {']
    for length in LENGTHS:
        data = sample(length)
        standard = base64.b64encode(data).decode('ascii')
        url = base64.urlsafe_b64encode(data).decode('ascii')
        lines.append(f'    {{base64_bytes_{length}, {length}, "{standard}", "{standard.rstrip("=")}", '
                     f'"{url}", "{url.rstrip("=")}"}},')
    lines += ['};', '', '#endif', '']
    target = Path(__file__).resolve().parent.parent / 'tests' / 'codec' / 'base64_vectors.h'
    target.write_bytes('\n'.join(lines).encode('ascii'))


if __name__ == '__main__':
    main()
