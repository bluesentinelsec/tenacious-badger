"""Write tests/codec/sha256_vectors.h: SHA-256 and HMAC-SHA256 answers from
Python's hashlib and hmac, an implementation independent of the engine's.

The SHA-256 inputs are every length from 0 to 300 bytes of a fixed pattern,
which crosses every place padding can fall in one and two blocks, and the
three examples of FIPS 180-2. The HMAC cases are the seven of RFC 4231, whose
published answers Python must reproduce first, and keys of every length
around the 64-byte block.

Run from the repository root: python tools/generate_sha256_vectors.py
"""
import hashlib
import hmac
from pathlib import Path

PATTERN_LENGTHS = range(0, 301)

# RFC 4231, section 4: (key, data, HMAC-SHA256, bytes of it compared).
RFC4231 = [
    (b'\x0b' * 20, b'Hi There',
     'b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7', 32),
    (b'Jefe', b'what do ya want for nothing?',
     '5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843', 32),
    (b'\xaa' * 20, b'\xdd' * 50,
     '773ea91e36800e46854db8ebd09181a72959098b3ef8c122d9635514ced565fe', 32),
    (bytes(range(1, 26)), b'\xcd' * 50,
     '82558a389a443c0ea4cc819899f2083a85f0faa3e578f8077a2e3ff46729665b', 32),
    (b'\x0c' * 20, b'Test With Truncation', 'a3b6167473100ee06e0c796c2955552b', 16),
    (b'\xaa' * 131, b'Test Using Larger Than Block-Size Key - Hash Key First',
     '60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54', 32),
    (b'\xaa' * 131,
     b'This is a test using a larger than block-size key and a larger than block-size data. '
     b'The key needs to be hashed before being used by the HMAC algorithm.',
     '9b09ffa71b942fcb27635fbcd5b0e944bfdc63644f0713938a7f51535c3a35e2', 32),
]


def pattern(length):
    return bytes((index * 31 + 7) & 0xFF for index in range(length))


def c_bytes(data):
    return ', '.join('0x%02x' % byte for byte in data)


def c_string(data):
    return '"' + ''.join('\\x%02x' % byte for byte in data) + '"'


def main():
    for key, data, expected, length in RFC4231:
        assert hmac.new(key, data, hashlib.sha256).hexdigest()[:length * 2] == expected
    lines = [
        '/* Generated by tools/generate_sha256_vectors.py from Python\'s hashlib and hmac. Do not edit. */',
        '#ifndef TB_TESTS_SHA256_VECTORS_H',
        '#define TB_TESTS_SHA256_VECTORS_H',
        '',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        '/* The SHA-256 of the first `length` bytes of the pattern (index * 31 + 7) & 0xFF. */',
        'typedef struct sha256_pattern_vector',
        '{',
        '    size_t length;',
        '    uint8_t digest[32];',
        '} sha256_pattern_vector;',
        '',
        'static const sha256_pattern_vector sha256_pattern_vectors[] = {',
    ]
    for length in PATTERN_LENGTHS:
        lines.append('    {%d, {%s}},' % (length, c_bytes(hashlib.sha256(pattern(length)).digest())))
    lines += ['};', '']
    fips = [b'abc', b'abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq']
    lines += [
        '/* FIPS 180-2, appendix B: two messages, and a million "a". */',
        'static const uint8_t sha256_abc[32] = {%s};' % c_bytes(hashlib.sha256(fips[0]).digest()),
        'static const uint8_t sha256_two_blocks[32] = {%s};' % c_bytes(hashlib.sha256(fips[1]).digest()),
        'static const uint8_t sha256_million_a[32] = {%s};' % c_bytes(hashlib.sha256(b'a' * 1000000).digest()),
        '',
        'typedef struct hmac_vector',
        '{',
        '    const char *key;',
        '    size_t key_length;',
        '    const char *data;',
        '    size_t data_length;',
        '    uint8_t mac[32];',
        '    size_t compared; /* Bytes of `mac` to compare: RFC 4231 truncates one. */',
        '} hmac_vector;',
        '',
        '/* RFC 4231\'s seven cases, then keys of 0 to 130 bytes over one message. */',
        'static const hmac_vector hmac_vectors[] = {',
    ]
    cases = [(key, data, length) for key, data, _, length in RFC4231]
    message = pattern(100)
    cases += [(pattern(length)[::-1], message, 32) for length in range(0, 131)]
    for key, data, compared in cases:
        mac = hmac.new(key, data, hashlib.sha256).digest()
        lines.append('    {%s, %d, %s, %d, {%s}, %d},' % (c_string(key), len(key), c_string(data),
                                                         len(data), c_bytes(mac), compared))
    lines += ['};', '', '#endif', '']
    Path('tests/codec/sha256_vectors.h').write_text('\n'.join(lines), newline='\n')


if __name__ == '__main__':
    main()
