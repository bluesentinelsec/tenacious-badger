"""Write src/codec/crc32_table.h: the eight tables of slicing-by-8 CRC-32.

CRC-32 is the checksum of ZIP, gzip, and PNG: the reflected polynomial
0xEDB88320. Slicing-by-8 reads eight bytes per step through eight tables of
256 entries. Table 0 is the classic byte-at-a-time table; table k advances a
CRC by k further zero bytes, so eight lookups combine eight input bytes.

The tables are constants, so the engine needs no initialization, and are
committed so that the build needs no Python. tests/codec/checksum_test.c
recomputes every entry bit by bit and compares, so a hand edit is caught.

Run from the repository root: python tools/generate_crc32_table.py
"""

from pathlib import Path

POLYNOMIAL = 0xEDB88320
TABLES = 8
ENTRIES = 256
PER_LINE = 7


def byte_table():
    table = []
    for index in range(ENTRIES):
        crc = index
        for _ in range(8):
            if crc & 1:
                crc = (crc >> 1) ^ POLYNOMIAL
            else:
                crc >>= 1
        table.append(crc)
    return table


def sliced_tables():
    tables = [byte_table()]
    for _ in range(1, TABLES):
        previous = tables[-1]
        tables.append([(entry >> 8) ^ tables[0][entry & 0xFF] for entry in previous])
    return tables


def render(tables):
    lines = [
        '/* Generated by tools/generate_crc32_table.py; do not edit by hand.',
        ' * The slicing-by-8 tables of CRC-32 with the reflected polynomial',
        ' * 0xEDB88320. Table k advances a CRC over one byte followed by k zero',
        ' * bytes. Private to src/codec. */',
        '#ifndef TB_CRC32_TABLE_H',
        '#define TB_CRC32_TABLE_H',
        '',
        '#include <stdint.h>',
        '',
        f'static const uint32_t tb_crc32_table[{TABLES}][{ENTRIES}] = {{',
    ]
    for table in tables:
        lines.append('    {')
        for start in range(0, ENTRIES, PER_LINE):
            row = ', '.join(f'0x{value:08X}u' for value in table[start:start + PER_LINE])
            lines.append(f'        {row},')
        lines.append('    },')
    lines += ['};', '', '#endif', '']
    return '\n'.join(lines)


def main():
    target = Path(__file__).resolve().parent.parent / 'src' / 'codec' / 'crc32_table.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(render(sliced_tables()).encode('ascii'))


if __name__ == '__main__':
    main()
