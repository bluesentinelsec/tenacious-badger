"""Write tests/codec/chacha20_vectors.h from the text of RFC 8439.

The RFC publishes test vectors for the ChaCha20 block function (appendix
A.1, five of them) and for encryption (appendix A.2, three), as hex dumps.
This reads them from the RFC's text, so the tests compare against the
published bytes and nothing retyped.

    python tools/generate_chacha20_vectors.py PATH-TO-rfc8439.txt

The text is at https://www.rfc-editor.org/rfc/rfc8439.txt.
"""
import re
import sys
from pathlib import Path

DUMP_LINE = re.compile(r'^  (\d{3})  ((?:[0-9a-f]{2} ){1,16})')


def read_dump(lines, start):
    """The bytes of the hex dump that starts at lines[start], and the line after it."""
    data = bytearray()
    index = start
    while index < len(lines):
        match = DUMP_LINE.match(lines[index])
        if match is None:
            if data:
                break
            index += 1
            continue
        assert int(match.group(1)) == len(data), lines[index]
        data += bytes.fromhex(match.group(2))
        index += 1
    return bytes(data), index


def field(lines, start, label):
    """The dump after the line `label`, searching from `start`."""
    for index in range(start, len(lines)):
        if lines[index].strip() == label:
            return read_dump(lines, index + 1)
    raise ValueError(label)


def number(lines, start, label):
    pattern = re.compile(r'^\s*' + re.escape(label) + r' = (\d+)')
    for index in range(start, len(lines)):
        match = pattern.match(lines[index])
        if match:
            return int(match.group(1)), index + 1
    raise ValueError(label)


def vectors(lines, section, count, counter_label, outputs):
    """Parse `count` test vectors after the heading `section`."""
    start = next(index for index, line in enumerate(lines) if line.startswith(section))
    found = []
    for _ in range(count):
        start = next(index for index in range(start, len(lines))
                     if lines[index].strip().startswith('Test Vector #'))
        key, after = field(lines, start, 'Key:')
        nonce, after = field(lines, after, 'Nonce:')
        counter, after = number(lines, after, counter_label)
        values = []
        for label in outputs:
            value, after = field(lines, after, label)
            values.append(value)
        assert len(key) == 32 and len(nonce) == 12
        found.append((key, nonce, counter, values))
        start = after
    return found


def c_bytes(data):
    return ', '.join('0x%02x' % byte for byte in data)


def main():
    lines = Path(sys.argv[1]).read_text(encoding='utf-8').splitlines()
    blocks = vectors(lines, 'A.1.  The ChaCha20 Block Functions', 5, 'Block Counter',
                     ['Keystream:'])
    ciphers = vectors(lines, 'A.2.  ChaCha20 Encryption', 3, 'Initial Block Counter',
                      ['Plaintext:', 'Ciphertext:'])
    out = [
        '/* Generated by tools/generate_chacha20_vectors.py from RFC 8439, appendix A. Do not edit. */',
        '#ifndef TB_TESTS_CHACHA20_VECTORS_H',
        '#define TB_TESTS_CHACHA20_VECTORS_H',
        '',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        'typedef struct chacha20_block_vector',
        '{',
        '    uint8_t key[32];',
        '    uint8_t nonce[12];',
        '    uint32_t counter;',
        '    uint8_t keystream[64];',
        '} chacha20_block_vector;',
        '',
        '/* Appendix A.1: the block function. */',
        'static const chacha20_block_vector chacha20_block_vectors[] = {',
    ]
    for key, nonce, counter, (keystream,) in blocks:
        assert len(keystream) == 64
        out.append('    {{%s},\n     {%s},\n     %du,\n     {%s}},' % (
            c_bytes(key), c_bytes(nonce), counter, c_bytes(keystream)))
    out += [
        '};',
        '',
        'typedef struct chacha20_cipher_vector',
        '{',
        '    uint8_t key[32];',
        '    uint8_t nonce[12];',
        '    uint32_t counter;',
        '    size_t length;',
        '    uint8_t plaintext[375];',
        '    uint8_t ciphertext[375];',
        '} chacha20_cipher_vector;',
        '',
        '/* Appendix A.2: encryption, from an initial block counter. */',
        'static const chacha20_cipher_vector chacha20_cipher_vectors[] = {',
    ]
    for key, nonce, counter, (plaintext, ciphertext) in ciphers:
        assert len(plaintext) == len(ciphertext) <= 375
        out.append('    {{%s},\n     {%s},\n     %du,\n     %d,\n     {%s},\n     {%s}},' % (
            c_bytes(key), c_bytes(nonce), counter, len(plaintext), c_bytes(plaintext),
            c_bytes(ciphertext)))
    out += ['};', '', '#endif', '']
    Path('tests/codec/chacha20_vectors.h').write_text('\n'.join(out), newline='\n')
    print(f'{len(blocks)} block vectors, {len(ciphers)} cipher vectors '
          f'({", ".join(str(len(c[3][0])) for c in ciphers)} bytes)')


if __name__ == '__main__':
    main()
