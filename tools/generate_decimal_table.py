"""Write src/core/decimal_table.h: the powers of ten of the shortest conversion.

tb_decimal_shortest() finds the shortest decimal of a double with the
Schubfach algorithm (Raffaello Giulietti, "The Schubfach way to render
doubles", 2020). It multiplies by 10^-k, for k from -292 to 326, held as a
number g of 128 bits with the power of two that scales it to [2^127, 2^128):

    e = floor(log2(10^k)) + 1 - 128
    g = ceil(10^k / 2^e)

Each g is computed here exactly, with Python's integers. The table is
committed so that the build needs no Python; the engine's tests compare the
conversion with an exact one over every binary exponent, which reaches every
entry, so a hand edit or a stale generator is caught.

Run from the repository root: python tools/generate_decimal_table.py
"""

from pathlib import Path

LOWEST = -292
HIGHEST = 326


def floor_log2(value_numerator, value_denominator):
    """floor(log2(numerator / denominator)) for positive integers."""
    estimate = value_numerator.bit_length() - value_denominator.bit_length()
    # Adjust so that 2^estimate <= value < 2^(estimate + 1).
    while _below(value_numerator, value_denominator, estimate):
        estimate -= 1
    while not _below(value_numerator, value_denominator, estimate + 1):
        estimate += 1
    return estimate


def _below(numerator, denominator, exponent):
    """Whether numerator / denominator < 2^exponent."""
    if exponent >= 0:
        return numerator < denominator << exponent
    return numerator << -exponent < denominator


def ceil_div(numerator, denominator):
    return -((-numerator) // denominator)


def power_of_ten(k):
    if k >= 0:
        numerator, denominator = 10**k, 1
    else:
        numerator, denominator = 1, 10**-k
    e = floor_log2(numerator, denominator) + 1 - 128
    if e >= 0:
        g = ceil_div(numerator, denominator << e)
    else:
        g = ceil_div(numerator << -e, denominator)
    assert 1 << 127 <= g < 1 << 128, k
    return g


def main():
    lines = [
        "/* Generated by tools/generate_decimal_table.py; do not edit by hand.",
        " * 10^k for k from TB_DECIMAL_TABLE_LOWEST to TB_DECIMAL_TABLE_HIGHEST, each",
        " * as ceil(10^k / 2^e) in [2^127, 2^128), where e = floor(log2(10^k)) + 1 - 128,",
        " * high 64 bits first. Private to src/core. */",
        "#ifndef TB_DECIMAL_TABLE_H",
        "#define TB_DECIMAL_TABLE_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define TB_DECIMAL_TABLE_LOWEST ({LOWEST})",
        f"#define TB_DECIMAL_TABLE_HIGHEST {HIGHEST}",
        "",
        f"static const uint64_t tb_decimal_table[{HIGHEST - LOWEST + 1}][2] = {{",
    ]
    for k in range(LOWEST, HIGHEST + 1):
        g = power_of_ten(k)
        high = g >> 64
        low = g & ((1 << 64) - 1)
        lines.append(f"    {{0x{high:016X}u, 0x{low:016X}u}}, /* 10^{k} */")
    lines += ["};", "", "#endif", ""]
    path = Path("src/core/decimal_table.h")
    path.write_bytes("\n".join(lines).encode())
    print(f"wrote {path}: {HIGHEST - LOWEST + 1} entries")


if __name__ == "__main__":
    main()
